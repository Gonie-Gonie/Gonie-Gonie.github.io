  const $ = (selector, root = document) => root.querySelector(selector);
  const $$ = (selector, root = document) => Array.from(root.querySelectorAll(selector));
  const t = (key) => I18N[state.lang]?.[key] || I18N.en[key] || key;

  function initialLanguage() {
    const query = new URLSearchParams(window.location.search).get('lang');
    if (query === 'en' || query === 'ko') return query;
    try {
      const saved = window.localStorage.getItem('siteLanguage');
      if (saved === 'en' || saved === 'ko') return saved;
    } catch (_) { /* The URL still selects a language when storage is unavailable. */ }
    return 'ko';
  }

  function renderHome() {
    const home = $('.guide-home .brand');
    home.href = `index.html?lang=${state.lang}`;
    if (state.profile) home.querySelector('[data-profile="name"]').textContent = D.personName(state.profile.identity, state.lang);
  }

  function setLanguage(language, options = {}) {
    if (language !== 'en' && language !== 'ko') return;
    state.lang = language;
    document.documentElement.lang = state.lang;
    document.documentElement.dataset.lang = state.lang;
    try { window.localStorage.setItem('siteLanguage', state.lang); } catch (_) { /* Keep the in-page selection. */ }
    if (!options.skipURL) {
      const url = new URL(window.location.href);
      url.searchParams.set('lang', state.lang);
      window.history.replaceState({}, '', url);
    }
    $$('[data-i18n]').forEach(element => {
      element.textContent = t(element.dataset.i18n);
    });
    // These local strings include links, UI labels, and example placeholders.
    $$('[data-i18n-html]').forEach(element => {
      element.innerHTML = t(element.dataset.i18nHtml);
    });
    $$('[data-i18n-aria]').forEach(element => {
      element.setAttribute('aria-label', t(element.dataset.i18nAria));
    });
    $$('[data-i18n-title]').forEach(element => {
      element.setAttribute('title', t(element.dataset.i18nTitle));
    });
    document.title = t('title');
    $('meta[name="description"]').content = t('description');
    $$('[data-lang-switch]').forEach(button => {
      button.setAttribute('aria-pressed', String(button.dataset.langSwitch === state.lang));
    });
    renderHome();
    updateUsername();
  }

  function applyTheme(settings) {
    D.applyColorTheme(settings);
    document.querySelectorAll('.mock.editor').forEach(element => window.SiteThemes.applyEditor(settings, element));
  }
