  const bundleVersion = D.loadVersion();
  function loadDocument(file) {
    return Promise.all([bundleVersion, fetch(file, { cache: 'no-cache' })
      .then(response => {
        if (!response.ok) throw new Error('Failed to load ' + file + ': ' + response.status);
        return response.json();
      })])
      .then(([version, document]) => window.SiteDataVersion.decode(document, file, { bundleVersion: version }).data);
  }
  loadDocument(D.FILES.settings)
    .then(applyTheme)
    .catch(() => applyTheme({}));
  loadDocument(D.FILES.profile)
    .then(profile => {
      state.profile = profile;
      renderHome();
    })
    .catch(() => {});

  const input = document.getElementById('github-username');
  const shell = document.getElementById('username-shell');
  const help = document.getElementById('username-help');
  function updateUsername() {
    const value = input.value.trim();
    const valid = !value || (/^[a-z\d](?:[a-z\d-]{0,37}[a-z\d])?$/i.test(value) && !value.includes('--'));
    input.setAttribute('aria-invalid', String(!valid));
    shell.setAttribute('aria-invalid', String(!valid));
    help.textContent = t(valid ? 'usernameHelp' : 'usernameInvalid');
    if (valid) state.username = value || 'your-name';
    document.querySelectorAll('[data-example]').forEach(node => {
      node.textContent = node.dataset.example === 'repo' ? state.username + '.github.io' : state.username;
    });
  }
