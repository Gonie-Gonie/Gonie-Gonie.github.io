  if (!('IntersectionObserver' in window)) return;
  const links = Array.from(document.querySelectorAll('.toc a'));
  const setCurrent = current => links.forEach(link => link === current ? link.setAttribute('aria-current', 'step') : link.removeAttribute('aria-current'));
  const visible = new Set();
  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => entry.isIntersecting ? visible.add(entry.target.id) : visible.delete(entry.target.id));
    const current = links.find(link => visible.has(link.hash.slice(1)));
    if (!current) return;
    setCurrent(current);
  }, { rootMargin: '-8% 0px -55% 0px', threshold: 0 });
  document.querySelectorAll('.step').forEach(section => observer.observe(section));
